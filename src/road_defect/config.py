# --- Two-view глубина (photogrammetry.py, прототип v0 цикла 15) --------------
@dataclass
class TwoViewDepthConfig:
    """Пороги оценки глубины по двум калиброванным видам (plane + parallax).

    Прототип v0: валидирован ТОЛЬКО на синтетике (scripts/bench_two_view_depth.py);
    в pipeline не включён. Единицы: метры/пиксели BEV-сетки.
    """
    bev_mm_px: float = 4.0        # шаг метрической BEV-сетки, мм/px
    bev_margin_m: float = 0.7     # запас окна вокруг ямы (покрывает смещение дна)
    # Кап рабочей зоны: центр маски дальше max_range / полуразмер больше
    # max_extent — это не бортовая яма в 2.5–6 м, а ложная детекция или маска
    # у горизонта (обратная проекция взрывается: без капа сетка BEV на такой
    # маске аллоцировала бы десятки ГБ — ревью 2026-07-08) → честный отказ.
    bev_max_range_m: float = 15.0
    bev_max_extent_m: float = 3.0
    patch_px: int = 21            # окно NCC (нечётное)
    dz_max_m: float = 0.20        # потолок измеримой глубины (ограничивает скан)
    # Доля матчей, упёршихся в потолок скана (Δ у dz_max): выше — дно глубже
    # потолка, статистика по остатку была бы цензурированной (занижение) →
    # честный отказ depth_exceeds_scan_ceiling.
    saturated_max: float = 0.25
    ncc_min: float = 0.45         # слабее корреляция — точка дна не сматчена
    # Локализуемость матча ВДОЛЬ направления скана: RMS ВЧ-градиента патча по
    # оси базы (после полосовой фильтрации), в ОБОИХ видах. Гладкие/размазанные
    # ракурсом полосы (вода, пересвет, дальнее дно под скользящим углом) не
    # несут продольной текстуры — их NCC-матчи ложны (стенд 2026-07-08, D=6).
    texture_grad_min: float = 2.0
    # Регистрация видов по кольцу асфальта. 'affine' поглощает линейное
    # растяжение BEV от ошибки тангажа (подвеска); 'similarity' — жёстче,
    # честно валится при рассинхроне. Выбор — по результатам стенда.
    reg_model: str = "affine"     # 'similarity' | 'affine'
    reg_min_inliers: int = 25     # меньше инлаеров — регистрации нет (отказ)
    reg_ransac_px: float = 2.0    # порог RANSAC в px BEV
    # |равномерный масштаб регистрации − 1| больше допуска = метрики видов
    # рассинхронизированы → честный отказ registration_scale_mismatch, а не
    # ложные см. ДВЕ физические причины (обе легитимно ведут к отказу, стенд
    # 2026-07-08): неверная высота калибровки (масштаб h_true/h_nom; 10%
    # высоты = 13 см — грубый промах монтажа) ИЛИ сильный тангаж ≳1°
    # (даёт >12% растяжения). Тангаж ±0.5° (~7–8%) должен ПРОХОДИТЬ —
    # порог 0.06 его душил.
    reg_scale_tol: float = 0.12
    # Анизотропия линейной части регистрации (разброс сингулярных чисел):
    # умеренная — легальный след тангажа, который аффинная модель и должна
    # поглощать; выше предела — регистрация деградировала → отказ.
    reg_aniso_tol: float = 0.20
    # База короче — вырожденная встречная геометрия (камеры почти в одной
    # точке?): параллакс-руль ломается, честный отказ.
    min_baseline_m: float = 0.5
    # Перекрытие видимых масок двух видов в общей системе (IoU после
    # регистрации). ВАЖНО про физику (уточнение ревью 2026-07-08): контур
    # apparent-маски — это проекция КРОМКИ (она на плоскости) = истинное
    # отверстие ямы при любой глубине, поэтому у честной пары контуры почти
    # совпадают и IoU высок; смещается к камерам только СОДЕРЖИМОЕ масок.
    # Низкий IoU — патология (ошибка сегментации, край кадра, грубая
    # регистрация), а не «глубокая яма» → честный отказ.
    mask_overlap_iou_min: float = 0.12
    min_coverage: float = 0.06    # доля дна с матчами; ниже — затенение/вода → отказ
    min_matches: int = 40         # абсолютный минимум сматченных точек дна
    consistency_px: float = 6.0   # допуск |Δ − локальная медиана Δ| (выбросы NCC)
    # Ядро дна: глубина ямы = глубина её ЦЕНТРА, статистика — только по
    # матчам, чья ИСТИННАЯ позиция (раз-смещение на измеренный параллакс)
    # попала в ядро. Ядро — по distance transform apparent-маски (контур
    # маски = отверстие ямы): dt >= core_inradius_frac · max(dt); в отличие
    # от эрозии кругового диаметра не вырождается на вытянутых (колейных)
    # ямах (BLOCKER ревью 2026-07-08: фолбэк «ядро пусто → вся маска» давал
    # медиану 0.9 см при истине 6). Несматченное ядро — дно не видно с ОБЕИХ
    # сторон (крутые стенки, вода) → отказ вместо статистики по склонам
    # (стенд: занижение 10→1.7 см и завышение 8→12.1 см без гейта).
    core_inradius_frac: float = 0.5
    min_core_coverage: float = 0.10   # матчи-в-ядре / площадь ядра
    min_core_matches: int = 25

    def __post_init__(self):
        if self.patch_px < 5 or self.patch_px % 2 == 0:
            raise ValueError(f"patch_px должен быть нечётным >= 5, получено {self.patch_px}")
        if self.reg_model not in ("similarity", "affine"):
            raise ValueError(f"reg_model: 'similarity' | 'affine', получено {self.reg_model!r}")
        if not (0.0 < self.bev_mm_px <= 50.0):
            raise ValueError(f"bev_mm_px вне (0, 50]: {self.bev_mm_px}")
        if self.dz_max_m <= 0:
            raise ValueError(f"dz_max_m должен быть > 0: {self.dz_max_m}")
        if self.bev_max_range_m <= 0 or self.bev_max_extent_m <= 0:
            raise ValueError("bev_max_range_m/bev_max_extent_m должны быть > 0")
        if not (0.0 <= self.saturated_max <= 1.0):
            raise ValueError(f"saturated_max вне [0, 1]: {self.saturated_max}")
        if not (0.0 < self.core_inradius_frac < 1.0):
            raise ValueError(
                f"core_inradius_frac вне (0, 1): {self.core_inradius_frac}")
        if self.min_baseline_m <= 0 or self.reg_aniso_tol <= 0:
            raise ValueError("min_baseline_m/reg_aniso_tol должны быть > 0")


DEFAULT_TWO_VIEW = TwoViewDepthConfig()
