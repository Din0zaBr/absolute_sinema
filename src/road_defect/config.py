# --- Масштаб от высоты камеры (эксперимент 2026-07-16) -----------------------
@dataclass
class CameraHeightScaleConfig:
    """ОЦЕНОЧНЫЙ источник масштаба для кадров БЕЗ эталона: известная высота
    объектива над полотном + фокус из EXIF + горизонт, оцененный по карте
    глубины («якорь неба») или из приора тангажа (plane_scale.py).

    Валидация и границы применимости — docs/HEIGHT_SCALE_RESULTS.md:
    систематики масштаба не выявлено в пределах ~±10–15% (n=1 объект
    известного размера; приёмочной валидации НЕТ), а Д/Ш — это размер
    МАСКИ (включая тёмный ореол), не рулеточного «разрушения». По ТЗ v2 §2.1
    источник НЕ сертифицируем: размеры выдаются только с confidence='low',
    certifiable=false и полосой ошибки. Требует карту глубины (--depth).
    """
    height_m: float | None = None    # высота объектива над полотном; None = ВЫКЛ
    height_band_pct: float = 3.0     # неопределённость высоты (съёмка в полный рост)
    # Фокус в px исходного кадра; None -> пересчёт из EXIF FocalLengthIn35mmFilm
    # (f_px = fl35 * длинная_сторона / 36). Кроп-режимы смартфона делают
    # пересчёт неоднозначным — отсюда широкая полоса по умолчанию.
    f_px: float | None = None
    f_band_pct: float = 10.0
    # Fallback-приор тангажа для кадров без неба (дворы): типично медиана
    # sky-anchored кадров той же сессии съёмки. None = только «якорь неба».
    pitch_prior_deg: float | None = None
    pitch_prior_band_deg: float = 3.0
    # --- гейты оценки горизонта по карте глубины (см. plane_scale.py) -------
    grid_long_side: int = 1024       # рабочая сетка карты (аспект — от кадра)
    sky_top_frac: float = 0.45       # небо ищем в верхней доле кадра
    sky_band_frac: float = 0.05      # «небо» = нижние 5% диапазона карты
    # Мин. поддержка неба в АБСОЛЮТНЫХ px сетки: на родной ~518-сетке модели
    # гейт по доле кадра строже, чем на 1024 (ошибка в безопасную сторону —
    # чаще честный отказ; ревью 2026-07-16).
    sky_min_px: int = 1500
    road_row_lo_frac: float = 0.50   # опора плоскости — строки [lo..hi] высоты
    road_row_hi_frac: float = 0.97
    plane_min_support: int = 3000
    plane_max_subsample: int = 40000
    plane_reweight_iters: int = 3
    horizon_sys_grid_px: float = 15.0  # систематика якоря неба (~1° при f/4)
    pitch_min_deg: float = 4.0
    pitch_max_deg: float = 55.0
    roll_max_deg: float = 8.0
    # --- гейты дефекта -------------------------------------------------------
    pit_min_below_horizon_deg: float = 2.0  # контур ближе к горизонту — отказ
    max_ground_dist_m: float = 12.0         # дальше — полоса теряет смысл
    contour_max_pts: int = 3000

    @property
    def enabled(self) -> bool:
        return self.height_m is not None

    def __post_init__(self):
        if self.height_m is not None and not (0.2 <= self.height_m <= 5.0):
            raise ValueError("camera_scale.height_m вне [0.2, 5.0] м: "
                             f"{self.height_m}")
        if self.f_px is not None and self.f_px <= 0:
            raise ValueError(f"camera_scale.f_px должен быть > 0: {self.f_px}")
        if not (0.0 < self.pitch_min_deg < self.pitch_max_deg <= 89.0):
            raise ValueError("camera_scale: требуется 0 < pitch_min < pitch_max "
                             f"<= 89, получено {self.pitch_min_deg}/"
                             f"{self.pitch_max_deg}")
        if self.pitch_prior_deg is not None and not (
                self.pitch_min_deg <= self.pitch_prior_deg <= self.pitch_max_deg):
            raise ValueError("camera_scale.pitch_prior_deg вне "
                             f"[{self.pitch_min_deg}, {self.pitch_max_deg}]: "
                             f"{self.pitch_prior_deg}")
        if min(self.height_band_pct, self.f_band_pct,
               self.pitch_prior_band_deg) < 0:
            raise ValueError("camera_scale: полосы ошибок должны быть >= 0")
        if not (0.0 < self.road_row_lo_frac < self.road_row_hi_frac <= 1.0):
            raise ValueError("camera_scale: требуется 0 < road_row_lo_frac < "
                             "road_row_hi_frac <= 1")
        if self.max_ground_dist_m <= 0 or self.grid_long_side < 64:
            raise ValueError("camera_scale: max_ground_dist_m > 0 и "
                             "grid_long_side >= 64 обязательны")


DEFAULT_CAMERA_SCALE = CameraHeightScaleConfig()


# --- Пороги инференса -------------------------------------------------------
@dataclass
class InferenceConfig:
    det_conf: float = 0.25            # порог уверенности детектора
    det_iou: float = 0.45             # NMS IoU
    imgsz: int = 1024                 # длинная сторона при инференсе
    # Hough по люку гоняется на копии с длинной стороной <= imgsz, поэтому
    # радиусы задаются долей короткой стороны кадра, а не пикселями.
    manhole_min_radius_frac: float = 0.03   # мин. радиус люка (доля кадра)
    manhole_max_radius_frac: float = 0.45   # макс. радиус люка (доля кадра)
    # Гейт «эталон на дорожной плоскости»: люк — горизонтальный диск на дороге
    # (низ кадра). Круглый эллипс высоко в кадре — вертикальная поверхность
    # (баннер/знак/стена), давшая ЛОЖНЫЙ масштаб (047/048, цикл 8: центр на
    # 12% высоты, наклон 44.9°). Далёкий настоящий люк у горизонта виден под
    # скользящим углом и сильно сплюснут — поэтому отклоняем «высоко И кругло»
    # (а не по одной позиции: сплюснутый люк у горизонта — валиден). Порог 0.33
    # (верхняя ТРЕТЬ) осознанно консервативен в безопасную сторону (потеря
    # масштаба лучше ложного), но не режет умеренно-косые люки в средней части
    # кадра; 047 на 12% высоты ловится с запасом (ревью 2026-07-05).
    manhole_horizon_frac: float = 0.33          # выше этой доли высоты = верх кадра
    manhole_min_grazing_tilt_deg: float = 55.0  # верхний эталон обязан быть сильно сплюснут
    mask_min_area_px: int = 200       # отбраковка крошечных масок (площадные)
    # Второй pothole-проход (keremberke seg) поверх основного детектора:
    # лечит слепоту rezzzq к нетипичным ямам (засыпанная яма на 6dyN — 0
    # детекций даже при conf=0.01). Выключен по умолчанию: x2 время инференса
    # и отступление от дизайна §4 «один выбор на роль» — включать осознанно.
    ensemble_pothole: bool = False
    # Порог IoU слияния ансамбля — ОТДЕЛЬНО от NMS (det_iou): два РАЗНЫХ семейства
    # моделей (rezzzq vs keremberke-seg) на одной яме дают боксы с IoU 0.35–0.49
    # (seg-бокс vs обычный), и порог 0.45+ считал бы их разными → дубль в отчёте.
    # Ниже NMS + доп. проверка вложенности центра (merge_detections) — аудит 2026-07-07.
    ensemble_merge_iou: float = 0.35
    # Линейные трещины легально тонкие: 3px x 60px — уже валидная маска.
    # Общий порог 200 терял уверенные детекции трещин целиком (смок 2026-06-12).
    mask_min_area_linear_px: int = 60
    # Опоры mask_min_area_* заданы в АБСОЛЮТНЫХ пикселях и проверены в деле на
    # кадрах от ~2.9 МП (городские демо 1152x2560) до 12 МП — на них пороги не
    # меняются. На кадре МЕНЬШЕГО разрешения та же маска теряет площадь
    # пропорционально площади кадра, и абсолютный порог резал бы её целиком —
    # scaled_mask_min_area() масштабирует порог ВНИЗ. ВВЕРХ — никогда: «доля
    # кадра» на 48 МП подняла бы порог и срезала дальние мелкие ямы (аудит
    # 2026-07-07, №7 — принятый дизайн отложенного фикса).
    mask_min_area_ref_px: int = 2_900_000
    # --- Относительная глубина: пороги «кольцевой плоскостной линейки» ------
    # Единицы: rel_norm ≈ глубина/поперечная ширина (см. depth.py; шкала НЕ
    # совместима со старыми долями полнокадрового диапазона). Значения v0
    # физически мотивированы; рекалибровка — scripts/calibrate_depth_bucket.py,
    # итог фиксируется ЗДЕСЬ (правило «пороги только через config», аудит №8).
    depth_bucket_lo: float = 0.08        # ниже — shallow
    depth_bucket_hi: float = 0.35        # выше — deep
    depth_noise_gate_sigma: float = 3.0  # просадка < N*σ шероховатости — не сигнал
    # --- Оценка глубины в см (запрос заказчика 2026-07-14) --------------------
    # depth_cm_estimate = rel_norm × поперечная ширина ямы в см. Это ОЦЕНКА
    # (confidence всегда 'low', certifiable=False), НЕ измерение: физика
    # rel_norm ≈ dz/W честная (см. depth.py), но точность ограничена картой
    # Depth Anything и переносом mm/px от эталона к яме. Сертифицированная
    # depth_cm по-прежнему только из two-view (photogrammetry.py) / датчика.
    depth_cm_estimate_enabled: bool = True
    # Базовая относительная погрешность самого rel_norm (шум карты, протечки
    # маски, приближения pinhole-вывода); к ней добавляется полоса эталона.
    depth_cm_est_base_err_pct: float = 50.0
    # Эталон по тёмному эллипс-блобу (косой вид): выключен по умолчанию —
    # на реальном фото тень под бордюром прошла все фильтры и стала «люком».
    # Включать только после «золотой» валидации масштаба (§11).
    allow_blob_reference: bool = False

    # --- Мульти-эталон (F2) -------------------------------------------------
    # Разметка как эталон: ВЫКЛЮЧЕНА по умолчанию (паритет с --blob-ref/--curb-ref).
    # Причина (адверсариальное ревью 2026-06-19): ширина класса разметки
    # неоднозначна по одному штриху (линия 1.1 80–150 мм vs краевая 1.2 100–200 мм
    # vs СТОП-линия 400 мм), а ориентация в кадре не отличает поперечную линию от
    # ракурсно «горизонтальной» продольной — это даёт ЛОЖНЫЙ масштаб (2.5–5×),
    # что хуже отсутствия эталона. До «золотой» валидации (§11) включается явно
    # (--marking-ref): эталон выдаётся ТОЛЬКО как low-confidence с широкой полосой,
    # с подтверждением тёмным асфальтом по обе стороны штриха, и повышается лишь
    # при кросс-подтверждении люком. Борт — также ВЫКЛЮЧЕН (приподнят, см. выше).
    use_marking_reference: bool = False
    allow_curb_reference: bool = False
    # Кросс-валидация эталонов: два РАЗНОТИПНЫХ эталона с mm/px в пределах
    # xcheck_tol → повысить уверенность на ступень и сузить полосу; расхождение
    # больше xcheck_conflict → понизить до low, расширить полосу и предупредить
    # (никогда не усреднять конфликтующие эталоны молча).
    xcheck_tol: float = 0.20
    xcheck_conflict: float = 0.40
    curb_crosscheck_tol: float = 0.20   # борт принимается, только если согласован

    # Детект разметки (классика, без сетей): пороги краски и фильтры полосы.
    # Краска ярче МЕДИАНЫ дороги минимум на mark_l_margin (порог-перцентиль сел
    # бы НА уровень асфальта и пометил бы половину покрытия как «краску»).
    mark_l_margin: int = 40             # на сколько L краски выше медианы дороги
    mark_road_level_pctl: float = 55.0  # перцентиль L для робастной оценки уровня дороги
    mark_s_max: int = 80                # макс. насыщенность HLS для белой краски
    mark_stripe_min_elongation: float = 6.0  # длина/ширина minAreaRect полосы
    mark_min_len_frac: float = 0.10     # длинная сторона ≥ доля короткой стороны кадра
    mark_fill_min: float = 0.55         # площадь компоненты / площадь повёрнутого прямоуг.
    mark_width_cv_max: float = 0.25     # макс. CoV ширины вдоль полосы (краска ровная)
    mark_width_taper_max: float = 1.5   # макс. near/far ширины (сильный наклон → отказ)
    mark_min_samples: int = 5           # мин. число замеров ширины вдоль полосы
    # Подтверждение «это краска, а не блик/полоса засветки»: асфальт по ОБЕ
    # стороны штриха должен быть темнее тела штриха минимум на эту разницу L.
    mark_min_flank_contrast: int = 18
    # СТОП-линия пересекает полосу — её протяжённость должна быть заметной долей
    # ширины кадра. Короткий «горизонтальный» штрих — это, скорее, ракурсная
    # продольная линия (ошибочно дала бы 400 мм вместо 80–150 мм) → отказ.
    mark_stopline_min_span_frac: float = 0.30
    # Полоса ошибки масштаба по разметке: широкая и confidence жёстко 'low' —
    # класс ширины разметки по одному штриху неоднозначен (см. use_marking_reference).
    mark_error_band_pct: float = 50.0

    # --- Слияние двух видов (F1) -------------------------------------------
    # Поправка площади за наклон 1/cos(tilt) ограничена tilt ≤ 60° (cos ≥ 0.5):
    # дальше и закон cos, и сама оценка наклона ненадёжны (ср. отсечка аспекта
    # 0.45 / ~63° в detect_manhole_ellipses).
    fusion_cos_floor: float = 0.5
    fusion_agree_tol: float = 0.20      # ВСЕ размеры видов в пределах 20% → +ступень уверенности
    fusion_disagree_max: float = 0.40   # расхождение >40% → low, шире полоса, предупреждение
    # Слияние двух видов валидно лишь для ОДНОЙ ямы: если форма (eccentricity/
    # solidity) видов расходится сильнее, это, вероятно, РАЗНЫЕ ямы — не сливаем.
    fusion_shape_tol: float = 0.30
    # Если наклон хотя бы одного вида НЕизвестен (эталон-разметка/борт), площадь
    # НЕ корректируется за ракурс — ПЛОЩАДНАЯ полоса ошибки (cross_view.
    # area_error_band_pct, ≈2× линейной) расширяется до этого минимума, честно
    # отражая возможное остаточное укорочение; в metric.error_band_pct уходит
    # линейный эквивалент (половина).
    fusion_uncorrected_area_band_pct: float = 40.0

    # --- Масштаб от высоты камеры (fallback без эталона; plane_scale.py) ----
    # ВЫКЛЮЧЕН по умолчанию (height_m=None). Включается осознанно, когда
    # высота съёмки известна (CLI --camera-height). Все пороги — в
    # CameraHeightScaleConfig выше.
    camera_scale: CameraHeightScaleConfig = field(
        default_factory=CameraHeightScaleConfig)

    def __post_init__(self):
        # Новые ручки цикла 13 валидируются при создании конфига: вырожденная
        # опора/пороги бакета падали бы делением на нуль на КАЖДОМ кадре с
        # детекцией (адверсариальное ревью 2026-07-07) — честнее отказать сразу.
        if self.mask_min_area_ref_px <= 0:
            raise ValueError("mask_min_area_ref_px должен быть > 0, получено "
                             f"{self.mask_min_area_ref_px}")
        if not (0.0 < self.depth_bucket_lo <= self.depth_bucket_hi):
            raise ValueError("Пороги бакета глубины: требуется 0 < lo <= hi, "
                             f"получено lo={self.depth_bucket_lo}, "
                             f"hi={self.depth_bucket_hi}")
        if self.depth_noise_gate_sigma < 0:
            raise ValueError("depth_noise_gate_sigma должен быть >= 0, получено "
                             f"{self.depth_noise_gate_sigma}")
        if self.depth_cm_est_base_err_pct < 0:
            raise ValueError("depth_cm_est_base_err_pct должен быть >= 0, "
                             f"получено {self.depth_cm_est_base_err_pct}")

    def scaled_mask_min_area(self, base_px: int, image_hw) -> int:
        """Порог площади маски для кадра (H, W): только ВНИЗ от base_px.

        Кадры площадью >= mask_min_area_ref_px сохраняют абсолютный порог;
        меньшие получают порог пропорционально площади кадра (пол — 1 px).
        """
        h, w = int(image_hw[0]), int(image_hw[1])
        ratio = min(1.0, (h * w) / float(self.mask_min_area_ref_px))
        return max(1, int(round(base_px * ratio)))


